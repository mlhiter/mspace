export function normalizeMspaceLocale(value: string | undefined | null): MspaceLocale {
  const normalized = String(value || "").trim().toLowerCase();
  if (normalized === "zh-cn" || normalized === "zh" || normalized.startsWith("zh-")) return "zh-CN";
  return "en";
}

function getStoredLocale(): MspaceLocale | undefined {
  if (typeof window === "undefined") return undefined;
  const stored = window.localStorage.getItem(MSPACE_LOCALE_STORAGE_KEY);
  return stored ? normalizeMspaceLocale(stored) : undefined;
}

function getBrowserLocale(): MspaceLocale {
  if (typeof navigator === "undefined") return "en";
  return normalizeMspaceLocale(navigator.languages?.[0] || navigator.language);
}

function syncDocumentLocale(locale: MspaceLocale) {
  if (typeof document === "undefined") return;
  document.documentElement.lang = locale;
}

function syncStoredLocale(locale: MspaceLocale) {
  if (typeof window === "undefined") return;
  window.localStorage.setItem(MSPACE_LOCALE_STORAGE_KEY, locale);
}

export function initializeMspaceI18n() {
  const initialLocale = getStoredLocale() || getBrowserLocale();

  if (!i18n.isInitialized) {
    void i18n.use(initReactI18next).init({
      resources,
      lng: initialLocale,
      fallbackLng: "en",
      supportedLngs: supportedMspaceLocales.map((locale) => locale.code),
      ns: ["common"],
      defaultNS: "common",
      interpolation: {
        escapeValue: false,
      },
      react: {
        useSuspense: false,
      },
    });
  }

  syncDocumentLocale(normalizeMspaceLocale(i18n.resolvedLanguage || i18n.language || initialLocale));
  i18n.off("languageChanged", handleLanguageChanged);
  i18n.on("languageChanged", handleLanguageChanged);
  return i18n;
}

function handleLanguageChanged(locale: string) {
  const nextLocale = normalizeMspaceLocale(locale);
  syncStoredLocale(nextLocale);
  syncDocumentLocale(nextLocale);
}

export function getMspaceLocale(): MspaceLocale {
  return normalizeMspaceLocale(i18n.resolvedLanguage || i18n.language || getStoredLocale() || getBrowserLocale());
}

export function useMspaceTranslation() {
  return useTranslation("common");
}

export function useMspaceLanguage() {
  const { i18n: instance } = useMspaceTranslation();
  const language = normalizeMspaceLocale(instance.resolvedLanguage || instance.language);

  return {
    language,
    changeLanguage: (locale: MspaceLocale) => instance.changeLanguage(locale),
  };
}

export function t(key: string, options?: TOptions) {
  return i18n.t(key, options);
}
